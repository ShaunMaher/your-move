/**
 * The kit word list (`engine/kit-words.ts`, words §10.6) and its generator. The list must be
 * exactly every two- and three-letter word of the built `enable` list plus the worst-case words,
 * formatted as below. When the built list changes, regenerate the file:
 *
 *   UPDATE_KIT_WORDS=1 pnpm vitest run games/words/src/kit-words.test.ts
 */
import { readFileSync, writeFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { KIT_WORDS } from "./engine/kit-words.js";
import { realWordList } from "./test-support.js";

/** The longer words the `worstCase` plays need (`kit-hooks.ts`). */
const WORST_CASE_WORDS = ["abalone", "acknowledgments", "aerosol", "letters"];

/** The longest line the generator writes, quotes and indentation excluded. */
const LINE = 92;

const HEADER = `/**
 * The kit dictionary: the word list the generic test kit plays the words engine with in this
 * package's \`test.resources\` hook (docs/spec/02-game-framework.md §6, games/words.md §10.6).
 *
 * An engine can't load a word list (it does no I/O, 02 §2), so the hook carries its own: every
 * two- and three-letter word of the built \`enable\` dictionary (words §9.2), plus the longer
 * \`enable\` words the \`worstCase\` plays need. A test checks that every word here is in the built
 * list, so the kit only ever accepts real words. Generated by kit-words.test.ts; regenerate it
 * rather than editing it.
 */
`;

/** The kit word list module for these words: sorted, packed into lines of at most `LINE`. */
function generate(words: readonly string[]): string {
  const lines: string[] = [];
  let line = "";
  for (const word of [...new Set(words)].sort()) {
    if (line !== "" && line.length + 1 + word.length > LINE) {
      lines.push(line);
      line = word;
    } else {
      line = line === "" ? word : `${line} ${word}`;
    }
  }
  lines.push(line);
  const body = lines.map((text) => `  "${text}",`).join("\n");
  return `${HEADER}export const KIT_WORDS: readonly string[] = [\n${body}\n];\n`;
}

describe("the kit word list (words §10.6)", () => {
  it("is every two- and three-letter word of the built list, plus the worst-case words", async () => {
    const all = await realWordList();
    const short = all.filter((word) => word.length <= 3);
    const expected = [...short, ...WORST_CASE_WORDS];
    for (const word of WORST_CASE_WORDS) expect(all).toContain(word);
    const file = new URL("engine/kit-words.ts", import.meta.url);
    const source = generate(expected);
    if (process.env["UPDATE_KIT_WORDS"] === "1") writeFileSync(file, source);
    expect(readFileSync(file, "utf8")).toBe(source);
    expect(KIT_WORDS.flatMap((text) => text.split(" "))).toEqual([...new Set(expected)].sort());
  }, 60_000);
});
