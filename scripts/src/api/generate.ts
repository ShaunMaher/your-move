/**
 * `pnpm api:generate` (docs/spec/05-api.md §Versioning, 11 §3): writes the public OpenAPI document
 * and the typed client's types from the server's route schemas. Both outputs are committed; CI
 * regenerates them and fails on any difference.
 */
import {
  createApp,
  createConsoleEmailSender,
  createJsonLogger,
  DEFAULT_APP_NAME,
  detachedRepositories,
  NO_DICTIONARIES,
  parseConfig,
} from "@your-move/server";
import openapiTS, { astToString } from "openapi-typescript";

/** A throwaway local-dev configuration: the document depends only on the app name. */
const DOCUMENT_ENV = {
  APP_NAME: DEFAULT_APP_NAME,
  PUBLIC_URL: "http://localhost",
  APP_SECRET: btoa("api-generate-does-not-use-this-secret!"),
  EMAIL_PROVIDER: "console",
  EMAIL_FROM: "no-reply@localhost",
  OPERATOR_CONTACT: "ops@localhost",
};

/** The OpenAPI document exactly as the server serves it with the default `APP_NAME`. */
export async function buildOpenApiDocument(): Promise<unknown> {
  const config = parseConfig(DOCUMENT_ENV, { runtime: "node", installedGames: [] });
  const now = (): Date => new Date(0);
  const log = createJsonLogger({ level: "error", now, sink: () => undefined });
  const app = createApp({
    platform: {
      repos: detachedRepositories(),
      config,
      now,
      log,
      email: createConsoleEmailSender(log, now),
      clientIp: () => ({ ok: false, reason: "missing" }),
      dictionaries: NO_DICTIONARIES,
    },
    games: [],
  });
  const response = await app.request("/api/v1/openapi.json");
  if (!response.ok) throw new Error(`openapi.json answered ${String(response.status)}`);
  return response.json();
}

const HEADER = `/**
 * Generated by \`pnpm api:generate\` from the server's route schemas (openapi-typescript).
 * Do not edit: change the schemas in @your-move/shared and regenerate.
 */
`;

export interface ApiArtifacts {
  /** `packages/api-client/openapi/v1.json` */
  readonly document: string;
  /** `packages/api-client/src/schema.ts` */
  readonly types: string;
}

/** Renders the committed artifacts (unformatted; the caller formats them for their paths). */
export async function renderApiArtifacts(document: unknown): Promise<ApiArtifacts> {
  const ast = await openapiTS(document as Parameters<typeof openapiTS>[0]);
  return { document: JSON.stringify(document), types: HEADER + astToString(ast) };
}
