import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { afterEach, describe, expect, it } from "vitest";

import { renderAll, writeGenerated } from "./generate.js";
import { loadGames, type LoadedGame } from "./load.js";
import { nodeModulesResolver } from "./packages.js";

const FIXTURES = fileURLToPath(new URL("../../test-fixtures/games", import.meta.url));

async function fixtureGames(): Promise<readonly LoadedGame[]> {
  const result = await loadGames(
    {
      games: [
        { package: "@fixture/game-good" },
        { package: "@fixture/game-clientdep", enabled: false },
      ],
    },
    nodeModulesResolver(FIXTURES),
  );
  if (!result.ok) throw new Error(result.problems.join("\n"));
  return result.games;
}

describe("games:generate output", () => {
  it("renders an empty instance", () => {
    const files = renderAll([]);
    expect(files["server-registry.ts"]).toContain("}[] = [];");
    expect(files["client-games.ts"]).toContain(
      "export const gameClients: Readonly<Record<string, () => Promise<unknown>>> = {};",
    );
    expect(JSON.parse(files["installed.json"])).toEqual({});
    for (const content of Object.values(files)) expect(content.endsWith("\n")).toBe(true);
  });

  it("imports each package only through its entry points", async () => {
    const files = renderAll(await fixtureGames());
    expect(files["server-registry.ts"]).toContain(
      'import { engines as engines0 } from "@fixture/game-good/engine";',
    );
    expect(files["server-registry.ts"]).toContain(
      'import { manifest as manifest1 } from "@fixture/game-clientdep/manifest";',
    );
    expect(files["server-registry.ts"]).toContain(
      "{ manifest: manifest1, engines: engines1, enabledByDefault: false },",
    );
    expect(files["client-games.ts"]).toContain(
      '"good": () => import("@fixture/game-good/client"),',
    );
    expect(files["server-registry.ts"]).toMatch(/^\/\/ Generated by `pnpm games:generate`/u);
  });

  it("lists plain data in installed.json: package, version, rules versions, default", async () => {
    expect(JSON.parse(renderAll(await fixtureGames())["installed.json"])).toEqual({
      good: {
        package: "@fixture/game-good",
        version: "1.0.0",
        rulesVersions: [1],
        enabledByDefault: true,
      },
      clientdep: {
        package: "@fixture/game-clientdep",
        version: "1.0.0",
        rulesVersions: [1],
        enabledByDefault: false,
      },
    });
  });
});

describe("writeGenerated", () => {
  let dir: string | null = null;
  afterEach(() => {
    if (dir) rmSync(dir, { recursive: true, force: true });
  });

  it("writes every file into the output directory", () => {
    dir = mkdtempSync(join(tmpdir(), "generated-"));
    const files = renderAll([]);
    writeGenerated(join(dir, "generated"), files);
    for (const [name, content] of Object.entries(files)) {
      expect(readFileSync(join(dir, "generated", name), "utf8")).toBe(content);
    }
  });
});
